#!/usr/bin/env bash
# Scaffold a pentest engagement folder.
#   ./new-engagement.sh <name> <base-url> <scope-path-prefix> [parent-dir]
#   ./new-engagement.sh harbor https://breachlab-six.vercel.app /labs/harbor
set -euo pipefail
[ $# -ge 3 ] || { sed -n 2,5p "$0"; exit 1; }
NAME=$1; BASE=$2; PREFIX=$3
PARENT=${4:-/home/kali/Desktop/Security-Pentest/burptest}
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$PARENT/$NAME
[ ! -e "$ROOT" ] || { echo "exists: $ROOT"; exit 1; }
HOST=${BASE#*://}; HOST=${HOST%%/*}

mkdir -p "$ROOT"/{00-scope,01-recon,02-burp,03-evidence/{screenshots,requests,logs},04-notes,05-report,tools}
cp "$HERE"/../log-to-html/converter.py "$ROOT"/
find "$HERE"/../log-to-html/tools -maxdepth 1 -type f -exec cp {} "$ROOT"/tools/ \;
cp "$HERE"/shot.sh "$HERE"/log.sh "$HERE"/refresh.sh "$ROOT"/tools/
chmod +x "$ROOT"/tools/*.sh

cat > "$ROOT/00-scope/scope.md" <<EOF
# Scope: $NAME
- Target: $BASE$PREFIX only
- In scope host: $HOST
- Rule: stay under $PREFIX. Do not touch the rest of the host or other targets.
- Authorisation: <lab / program page URL / client sign-off, fill in>
- Out of bounds: no DoS, no brute-force floods, no real user data, no persistence
- Accounts provided: <role: username only; passwords live in your password manager, not here>
- Test window: <start - end>
EOF

cat > "$ROOT/04-notes/endpoints.md" <<EOF
# Endpoints (generated by refresh.sh; edit only Tested? and Notes columns)
EOF
cat > "$ROOT/04-notes/hypotheses.md" <<'EOF'
# Hypotheses (one line each: what I think is wrong, why, how I will test it)
| ID | Hypothesis | Evidence that raised it | Test | Result |
| --- | --- | --- | --- | --- |
EOF
cat > "$ROOT/04-notes/tests.md" <<'EOF'
# Test log (generated from Logger++ X-Test markers; see README)
EOF
cat > "$ROOT/04-notes/findings.md" <<'EOF'
# Findings
Finding template (copy per finding, ID = F-01, F-02 ...):

## F-01 <title>
- Severity / CVSS:
- Location (method + path + param):
- Description:
- Steps to reproduce (numbered, exact requests):
- Evidence: 03-evidence/requests/F-01-*.txt, 03-evidence/screenshots/F-01-*.png
- Impact:
- Fix:
EOF
cat > "$ROOT/04-notes/command-log.md" <<'EOF'
# Command log (append with tools/log.sh "what I did" "why")
EOF

cat > "$ROOT/README.md" <<EOF
# $NAME engagement

\`\`\`
00-scope/              scope.md, authorisation, rules
01-recon/              arsenal output, sitemap exports, wordlists
02-burp/               <project>.burp, LoggerPlusPlus_Autosave.csv
03-evidence/
  screenshots/         F-01_<what>_YYYYMMDD-HHMMSS.png  (tools/shot.sh F-01 what)
  requests/            raw request/response pairs per finding
  logs/                exported logs, terminal output
04-notes/              endpoints, hypotheses, tests, findings, command-log
05-report/             dashboard.html (generated), final report
tools/                 converter + helpers
\`\`\`

## Start of engagement
1. Burp: start a **new project on disk** (not temporary) and save it as \`02-burp/$NAME.burp\`.
2. Burp Target -> Scope: add \`^https://${HOST//./\\.}/(api/)?${PREFIX#/}\` (use advanced scope, regex). Proxy settings: do not send out-of-scope items to history.
3. Logger++ -> Options -> CSV Exporter -> **Auto-export as CSV**. In the field dialog click **Select None**, then tick ONLY these 29 fields (keep the dialog's own order), click **Save** and name the preset \`SAFE\`, then OK and choose \`\$ROOT/02-burp/LoggerPlusPlus_Autosave.csv\`:
   \`Entry.Tool, Entry.Tags, Entry.InScope, Request.BodyLength, Request.Time, Request.Length, Request.Tool, Request.Comment, Request.Complete, Request.Method, Request.Path, Request.Protocol, Request.Hostname, Request.Extension, Request.HasParams, Request.HasGetParam, Request.HasPostParam, Request.HasSentCookies, Request.ParameterCount, Response.BodyLength, Response.Time, Response.Length, Response.Status, Response.StatusText, Response.RTT, Response.Title, Response.ContentType, Response.MimeType, Response.HasSetCookies\`
   Never tick: Headers, Body, AsBase64, URL, Query, PathQuery, Parameters, CookieString, Cookies, Redirect, Reflections. These carry cookies, tokens and param values. The log is then safe to share; the .burp project file is NOT (keep it local).
4. Logger++ filter: \`Request.Host == "$HOST"\`.
5. Proxy the browser through 127.0.0.1:8080.

## While testing
- Tag tests: add header \`X-Test: failed; id=TC02; cat=XSS; note=...\` (or Logger++ Comment \`TEST: ...\`).
- Screenshot every finding step: \`tools/shot.sh F-01 login-bypass\`.
- Note why you ran something: \`tools/log.sh "sent x' to username" "check SQLi differential"\`.
- Refresh notes + dashboard any time: \`tools/refresh.sh\`.
EOF

cat > "$ROOT/tools/.config" <<EOF
PREFIX=$PREFIX
EOF
echo "created $ROOT"
