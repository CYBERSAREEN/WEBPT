#!/usr/bin/env python3
"""Turn the Logger++ auto-export CSV into endpoints.md, tests.md and a Copilot-safe export.

Usage (from the project folder):
    python3 -I tools/burp2notes.py            # endpoints.md + tests.md + evidence/copilot-export.csv
    watch -n 30 python3 -I tools/burp2notes.py   # keep notes live while you test

Logger++ auto-export has no header row, so columns are read by position (checked
against Logger++ 3.x field order: 9 Time, 12 Comment, 14 URL, 15 Method, 16 Path,
17 Query, 35 ParamNames, 39 Response body, 45 Status, 50 MIME).

Test-case convention (type it in the Logger++ Comment column of the request):
    TC01 | XSS | script tag stripped? | PASS
    category : XSS, SQLI, AUTHZ, IDOR, CONFIG, INFO, ...
    result   : PASS = app defended, FAIL = vulnerability found, INFO = note only
"""
import csv, html, os, re, sys, urllib.parse

csv.field_size_limit(10**9)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "burp", "LoggerPlusPlus_Autosave.csv")
SCOPE_PREFIX = "/labs/parcelpoint"
NOISE_PARAMS = {"_rsc", "fcbz"}  # Next.js prefetch + stale match/replace tag
TIME, COMMENT, URL, METHOD, PATH, QUERY, STATUS, BODY, MIME = 9, 12, 14, 15, 16, 17, 45, 39, 50

def load():
    with open(SRC, newline="") as f:
        for r in csv.reader(f):
            if len(r) > MIME and r[PATH].startswith(SCOPE_PREFIX):
                yield r

def params(query):
    pairs = urllib.parse.parse_qsl(query, keep_blank_values=True)
    return [(k, v) for k, v in pairs if k not in NOISE_PARAMS]

def is_noise(r):
    # Next.js prefetch rows (_rsc)
    return "_rsc" in r[QUERY]

def md_escape(s):
    return s.replace("|", "\\|").replace("\n", " ")

def old_manual(path, col_names):
    """Keep the Tested/Notes columns the user typed by hand in a previous run."""
    keep = {}
    if not os.path.exists(path):
        return keep
    for line in open(path):
        if line.startswith("|") and not line.startswith("| ---") and not line.startswith("| Endpoint"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) == len(col_names):
                keep[cells[0]] = cells[-2:]
    return keep

def endpoints(rows):
    eps = {}
    for r in rows:
        if is_noise(r):
            continue
        key = f"{r[METHOD]} {r[PATH]}"
        e = eps.setdefault(key, {"params": set(), "status": set(), "n": 0, "ex": r[URL]})
        e["params"].update(k for k, _ in params(r[QUERY]))
        e["status"].add(r[STATUS])
        e["n"] += 1
    return eps

def write_endpoints(rows):
    cols = ["Endpoint", "Params", "Status seen", "Hits", "Tested?", "Notes"]
    path = os.path.join(ROOT, "notes", "endpoints.md")
    keep = old_manual(path, cols)
    out = ["# Endpoints (generated by tools/burp2notes.py; edit only Tested?/Notes)", "",
           "| " + " | ".join(cols) + " |", "|" + " --- |" * len(cols)]
    for key, e in sorted(endpoints(rows).items()):
        tested, notes = keep.get(key, ["no", ""])
        out.append("| " + " | ".join(md_escape(x) for x in [
            key, ", ".join(sorted(e["params"])) or "-", ", ".join(sorted(e["status"])),
            str(e["n"]), tested, notes]) + " |")
    open(path, "w").write("\n".join(out) + "\n")
    return len(out) - 4

def reflection_hint(r):
    """Cheap automatic signal: does a parameter value come back raw or encoded?"""
    body = r[BODY]
    hints = []
    for k, v in params(r[QUERY]):
        if len(v) < 3 or not body:
            continue
        if v in body:
            hints.append(f"{k}: reflected RAW")
        elif html.escape(v) in body:
            hints.append(f"{k}: reflected encoded")
    return "; ".join(hints) or "-"

TC = re.compile(r"^\s*(TC\w+)\s*\|\s*(\w+)\s*\|\s*(.*?)\s*\|\s*(PASS|FAIL|INFO)\s*$", re.I)

def write_tests(rows):
    cols = ["ID", "Category", "Test", "Result", "Request", "Status", "Auto hint", "Time"]
    out = ["# Test cases (generated from Logger++ comments; format: TC01 | XSS | what | PASS/FAIL/INFO)", "",
           "| " + " | ".join(cols) + " |", "|" + " --- |" * len(cols)]
    counts = {"PASS": 0, "FAIL": 0, "INFO": 0}
    for r in rows:
        m = TC.match(r[COMMENT])
        if not m:
            continue
        tid, cat, desc, res = m.group(1), m.group(2).upper(), m.group(3), m.group(4).upper()
        counts[res] += 1
        out.append("| " + " | ".join(md_escape(x) for x in [
            tid, cat, desc, res, f"{r[METHOD]} {r[PATH]}?{r[QUERY]}", r[STATUS],
            reflection_hint(r), r[TIME]]) + " |")
    out += ["", f"Totals: PASS {counts['PASS']}, FAIL {counts['FAIL']}, INFO {counts['INFO']}"]
    open(os.path.join(ROOT, "notes", "tests.md"), "w").write("\n".join(out) + "\n")
    return sum(counts.values())

def write_copilot(rows):
    """No cookies, no headers, no response bodies: safe to paste into Copilot."""
    path = os.path.join(ROOT, "evidence", "copilot-export.csv")
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["method", "path", "param_names", "param_values_trunc40", "status", "mime", "comment"])
        seen = set()
        for r in rows:
            if is_noise(r):
                continue
            ps = params(r[QUERY])
            vals = ";".join(f"{k}={v[:40]}" for k, v in ps)
            row = (r[METHOD], r[PATH], ",".join(k for k, _ in ps), vals, r[STATUS], r[MIME], r[COMMENT] if r[COMMENT] != "null" else "")
            if row not in seen:
                seen.add(row)
                w.writerow(row)
    return len(seen)

if __name__ == "__main__":
    if not os.path.exists(SRC):
        sys.exit(f"missing {SRC}")
    rows = list(load())
    os.makedirs(os.path.join(ROOT, "evidence"), exist_ok=True)
    print(f"{len(rows)} in-scope rows | endpoints: {write_endpoints(rows)} | "
          f"test cases: {write_tests(rows)} | copilot rows: {write_copilot(rows)}")
